import * as assert from 'assert';
import { describe, it } from 'node:test';
import {
  parseRawClassesFromCSharp,
  parseFluentConfigurations,
  parseDbContextDbSets,
  parseModelSnapshotFromCSharp,
  buildDbContextScopedModel,
  buildRelationships
} from '../ef/diagram/efDiagramScanner';
import { liveSyncDiagramWithCode } from '../ef/diagram/efDiagramStorage';
import { DiagramFile, EntityModel } from '../ef/diagram/efDiagramModel';

describe('EF Core Diagram Scanner & Storage (Deduplication & Multi-Block Merge)', () => {
  it('parseModelSnapshotFromCSharp merges multiple modelBuilder.Entity blocks for the same entity and removes duplicates', () => {
    const multiBlockSnapshotCode = `
      // <auto-generated />
      using System;
      using Cleeksy.DataHub.Infrastructure.DbContexts;
      using Microsoft.EntityFrameworkCore;
      using Microsoft.EntityFrameworkCore.Infrastructure;

      namespace Cleeksy.DataHub.Infrastructure.Migrations
      {
          [DbContext(typeof(DataHubDbContext))]
          partial class DataHubDbContextModelSnapshot : ModelSnapshot
          {
              protected override void BuildModel(ModelBuilder modelBuilder)
              {
                  // Block 1: Table and Properties
                  modelBuilder.Entity("Cleeksy.DataHub.Domain.Aggregates.Widgets.Entities.AppWidget", b =>
                  {
                      b.Property<int>("Id")
                          .HasColumnType("integer")
                          .HasColumnName("id");

                      b.Property<int>("AppId")
                          .HasColumnType("integer")
                          .HasColumnName("appid");

                      b.Property<string>("DisplayType")
                          .HasColumnType("text")
                          .HasColumnName("displaytype");

                      b.HasKey("Id")
                          .HasName("pk_appwidget");

                      b.ToTable("appwidget", (string)null);
                  });

                  // Block 2: Relationships
                  modelBuilder.Entity("Cleeksy.DataHub.Domain.Aggregates.Widgets.Entities.AppWidget", b =>
                  {
                      b.HasOne("Cleeksy.DataHub.Domain.Aggregates.Widgets.Entities.Widget", "Widget")
                          .WithOne("AppWidget")
                          .HasForeignKey("Cleeksy.DataHub.Domain.Aggregates.Widgets.Entities.AppWidget", "Id");
                  });

                  // Block 3: Navigation
                  modelBuilder.Entity("Cleeksy.DataHub.Domain.Aggregates.Widgets.Entities.AppWidget", b =>
                  {
                      b.Navigation("AppWidgetFilterSetting");
                  });
              }
          }
      }
    `;

    const result = parseModelSnapshotFromCSharp(multiBlockSnapshotCode, '/src/DataHubDbContextModelSnapshot.cs');
    assert.ok(result);
    assert.equal(result?.dbContextName, 'DataHubDbContext');
    // AppWidget MUST appear exactly ONCE
    assert.equal(result?.entities.length, 1, 'AppWidget must be merged into exactly 1 entity');

    const appWidget = result?.entities[0];
    assert.equal(appWidget?.shortName, 'AppWidget');
    assert.equal(appWidget?.tableName, 'appwidget');
    assert.equal(appWidget?.properties.length, 3, 'AppWidget must have exactly 3 properties');
    assert.equal(appWidget?.properties[0].name, 'Id');
    assert.equal(appWidget?.properties[0].isPrimaryKey, true);
    assert.equal(appWidget?.properties[1].name, 'AppId');
    assert.equal(appWidget?.properties[2].name, 'DisplayType');
    assert.equal(appWidget?.relationships.length, 1, 'AppWidget relationship must be merged');
  });

  it('buildDbContextScopedModel filters out false DbContexts like generic Repository and includes only valid contexts', () => {
    const rawClasses = [
      ...parseRawClassesFromCSharp(
        `public class Form : TenantEntity { public string Title { get; set; } }`,
        '/src/Form.cs',
        'ELDesk.CustomApp'
      ),
      ...parseRawClassesFromCSharp(
        `public class CustomAppDbContext : DbContext { public virtual DbSet<Form> Forms { get; set; } }`,
        '/src/CustomAppDbContext.cs',
        'ELDesk.CustomApp'
      )
    ];

    const dbContextSets = [
      { dbContextName: 'CustomAppDbContext', entityTypes: ['Form'] },
      { dbContextName: 'Repository', entityTypes: [] } // False DbContext
    ];

    const model = buildDbContextScopedModel(rawClasses, [], dbContextSets, []);
    assert.deepEqual(model.availableDbContexts, ['CustomAppDbContext']);
    assert.ok(!model.availableDbContexts.includes('Repository'), 'Repository must be excluded');
  });

  it('buildRelationships discovers relationships from navigation & FK properties', () => {
    const entities: EntityModel[] = [
      {
        id: '1',
        name: 'Form',
        filePath: '/src/Form.cs',
        line: 1,
        projectName: 'App',
        properties: [
          { name: 'Id', type: 'int', isPrimaryKey: true, isForeignKey: false, isNullable: false, isNavigation: false },
          { name: 'Fields', type: 'ICollection<AppField>', isPrimaryKey: false, isForeignKey: false, isNullable: false, isNavigation: true, isCollectionNavigation: true, navigationTargetEntity: 'AppField' }
        ]
      },
      {
        id: '2',
        name: 'AppField',
        filePath: '/src/AppField.cs',
        line: 1,
        projectName: 'App',
        properties: [
          { name: 'Id', type: 'int', isPrimaryKey: true, isForeignKey: false, isNullable: false, isNavigation: false },
          { name: 'FormId', type: 'int', isPrimaryKey: false, isForeignKey: true, isNullable: false, isNavigation: false, foreignKeyTargetEntity: 'Form' }
        ]
      }
    ];

    const rels = buildRelationships(entities);
    assert.ok(rels.length > 0);
    const formToField = rels.find(r => r.fromEntity === 'Form' && r.toEntity === 'AppField');
    assert.ok(formToField);
    assert.equal(formToField?.cardinality, 'one-to-many');
  });

  it('liveSyncDiagramWithCode preserves coordinates and prunes removed entities', () => {
    const saved: DiagramFile = {
      version: 1,
      name: 'Custom',
      createdAt: 100,
      updatedAt: 200,
      entities: {
        Form: { x: 120, y: 150 },
        DeletedOldEntity: { x: 500, y: 500 }
      }
    };

    const currentEntities: EntityModel[] = [
      {
        id: '1',
        name: 'Form',
        filePath: '/src/Form.cs',
        line: 1,
        projectName: 'App',
        properties: []
      }
    ];

    const synced = liveSyncDiagramWithCode(saved, currentEntities);
    assert.deepEqual(synced, {
      Form: { x: 120, y: 150 }
    });
  });
});
